#!/usr/bin/env python3
"""Writes the named character sets of mkfontpack.py as code point ranges, one set per line, for other tools
(FontPackBuilder) to select exactly the same characters:

  name<TAB>description<TAB>count<TAB>ranges        ranges: hex, comma-separated, e.g. 4E00-4E05,4E07

  export_sets.py > CharSets.txt
"""
import sys

from mkfontpack import SETS

DESCRIPTIONS = {
    "ascii": "ASCII",
    "latin1": "Latin-1 (ASCII and Latin-1 Supplement)",
    "cyrillic": "Cyrillic (basic)",
    "greek": "Greek and Coptic",
    "cjk-punct": "CJK punctuation and fullwidth forms",
    "kana": "Hiragana and Katakana",
    "hangul": "Hangul syllables (all 11172)",
    "hangul-ksx1001": "Hangul syllables of KS X 1001 (the 2350 common ones)",
    "hanzi-gb2312": "Simplified Chinese: the hanzi of GB2312",
    "kanji-jis0208": "Japanese: the kanji of JIS X 0208",
    "hanzi-big5": "Traditional Chinese: the hanzi of Big5",
    "hkscs": "Hong Kong: Big5-HKSCS (Big5 and the HKSCS supplement, Cantonese characters)",
    "cjk-all": "CJK Unified Ideographs (all 20992)",
}


def main():
    out = sys.stdout
    out.write("# Named character sets of mkfontpack.py (MeshtasticFontPacks), generated by tools/export_sets.py\n")
    for name, make in SETS.items():
        cps = sorted(set(make()))
        ranges = ",".join(("%04X-%04X" % (lo, hi)) if hi > lo else "%04X" % lo for lo, hi in runs_unbounded(cps))
        out.write("%s\t%s\t%d\t%s\n" % (name, DESCRIPTIONS.get(name, name), len(cps), ranges))


def runs_unbounded(cps):
    """Runs of consecutive code points (mkfontpack's runs() also splits at 256 and planes, for the pack format)."""
    out = []
    for cp in cps:
        if out and cp == out[-1][1] + 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


if __name__ == "__main__":
    main()
